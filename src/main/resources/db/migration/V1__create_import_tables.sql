CREATE TABLE importacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_arquivo VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('VENDAS', 'RECEBIMENTOS')),
    status VARCHAR(30) NOT NULL DEFAULT 'PROCESSANDO'
        CHECK (status IN (
            'PROCESSANDO',
            'CONCLUIDA',
            'CONCLUIDA_COM_ERROS',
            'FALHA'
        )),
    total_linhas INTEGER NOT NULL DEFAULT 0
        CHECK (total_linhas >= 0),
    linhas_importadas INTEGER NOT NULL DEFAULT 0
        CHECK (linhas_importadas >= 0),
    linhas_rejeitadas INTEGER NOT NULL DEFAULT 0
        CHECK (linhas_rejeitadas >= 0),
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE lancamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT NOT NULL
        REFERENCES importacoes(id) ON DELETE CASCADE,
    numero_linha INTEGER NOT NULL CHECK (numero_linha > 0),
    identificador_externo VARCHAR(100),
    data_movimento DATE NOT NULL,
    descricao VARCHAR(255),
    valor NUMERIC(15, 2) NOT NULL CHECK (valor >= 0),
    status_conciliacao VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status_conciliacao IN (
            'PENDENTE',
            'CONCILIADO',
            'DIVERGENTE'
        )),
    CONSTRAINT uq_lancamentos_importacao_linha
        UNIQUE (importacao_id, numero_linha)
);

CREATE TABLE erros_importacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    importacao_id BIGINT NOT NULL
        REFERENCES importacoes(id) ON DELETE CASCADE,
    numero_linha INTEGER NOT NULL CHECK (numero_linha > 0),
    mensagem TEXT NOT NULL
);

CREATE INDEX idx_lancamentos_data_valor
    ON lancamentos (data_movimento, valor);