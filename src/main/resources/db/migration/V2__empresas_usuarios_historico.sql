CREATE TABLE conciliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    importacao_vendas_id BIGINT NOT NULL,
    importacao_recebimentos_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    criada_em TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (importacao_vendas_id, empresa_id) REFERENCES importacoes(id, empresa_id),
    FOREIGN KEY (importacao_recebimentos_id, empresa_id) REFERENCES importacoes(id, empresa_id)
);
CREATE INDEX idx_conciliacoes_empresa_id ON conciliacoes(empresa_id, id DESC);
CREATE TABLE resultados_conciliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conciliacao_id BIGINT NOT NULL REFERENCES conciliacoes(id),
    referencia VARCHAR(100),
    valor_venda NUMERIC(25,2),
    valor_recebido NUMERIC(25,2),
    diferenca NUMERIC(25,2),
    status VARCHAR(40) NOT NULL CHECK (status IN ('CONCILIADO','DIVERGENTE',
        'VENDA_SEM_RECEBIMENTO','RECEBIMENTO_SEM_VENDA','REFERENCIA_DUPLICADA','REFERENCIA_AUSENTE'))
);
CREATE INDEX idx_resultados_conciliacao_status ON resultados_conciliacao(conciliacao_id, status, id);
